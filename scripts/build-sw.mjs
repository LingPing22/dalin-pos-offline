/**
 * Runs after `next build`. Lists every file of the exported site and writes
 * out/sw.js, a service worker that saves the WHOLE app on the iPad the first
 * time it is opened — after that it opens with no internet at all.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { createHash } from "node:crypto";

const OUT = "out";
const BASE = process.env.NEXT_PUBLIC_BASE_PATH || "";
const SKIP = new Set(["sw.js", ".nojekyll"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const hash = createHash("sha256");
const urls = [];
let bytes = 0;
for (const file of walk(OUT).sort()) {
  const rel = relative(OUT, file).split(sep).join("/");
  if (SKIP.has(rel) || rel.endsWith(".map")) continue;
  const data = readFileSync(file);
  bytes += data.length;
  hash.update(rel).update(data);
  urls.push(rel.endsWith("index.html") ? `${BASE}/${rel.slice(0, -"index.html".length)}` : `${BASE}/${rel}`);
}
const version = hash.digest("hex").slice(0, 12);

const sw = `/* Dalin POS Offline — generated by scripts/build-sw.mjs, do not edit */
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(BASE)};
const FILES = ${JSON.stringify(urls)};
const CACHE = "dalin-" + VERSION;

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      for (let i = 0; i < FILES.length; i += 20) await cache.addAll(FILES.slice(i, i + 20));
    }).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("dalin-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== location.origin || !url.pathname.startsWith(BASE + "/")) return;

  if (req.mode === "navigate") {
    let path = url.pathname;
    if (!path.endsWith("/") && !/\\.[a-z0-9]+$/i.test(path)) path += "/";
    event.respondWith(
      caches.open(CACHE).then(async (cache) =>
        (await cache.match(path)) ||
        fetch(req).catch(async () => (await cache.match(BASE + "/pos/")) || (await cache.match(BASE + "/")) || Response.error()),
      ),
    );
    return;
  }

  event.respondWith(
    caches.open(CACHE).then(async (cache) => (await cache.match(req, { ignoreSearch: true })) || fetch(req)),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`✓ sw.js: ${urls.length} files (${(bytes / 1024 / 1024).toFixed(2)} MB) cached for offline use, version ${version}`);
