/**
 * Runs after `next build`. Lists every file of the exported site and writes
 * out/sw.js, a service worker that saves the WHOLE app on the iPad the first
 * time it is opened — after that it opens with no internet at all.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { createHash } from "node:crypto";

const OUT = "out";
const BASE = process.env.NEXT_PUBLIC_BASE_PATH || "";
const SKIP = new Set(["sw.js", ".nojekyll"]);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const hash = createHash("sha256");
const urls = [];
let bytes = 0;
for (const file of walk(OUT).sort()) {
  const rel = relative(OUT, file).split(sep).join("/");
  if (SKIP.has(rel) || rel.endsWith(".map")) continue;
  const data = readFileSync(file);
  bytes += data.length;
  hash.update(rel).update(data);
  urls.push(rel.endsWith("index.html") ? `${BASE}/${rel.slice(0, -"index.html".length)}` : `${BASE}/${rel}`);
}
const version = hash.digest("hex").slice(0, 12);

/** Files a page asks for from /_next/static/ (scripts, styles) — they must all ship in the same build */
const escRe = (t) => t.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const REF = `${escRe(BASE)}/_next/static/[^"'\\\\\\s)?#]+`;
const have = new Set(urls);
for (const file of walk(OUT).filter((f) => f.endsWith(".html"))) {
  for (const ref of readFileSync(file, "utf8").match(new RegExp(REF, "g")) ?? [])
    if (!have.has(ref)) throw new Error(`${relative(OUT, file)} uses ${ref}, which is not in the build`);
}

const sw = `/* Dalin POS Offline — generated by scripts/build-sw.mjs, do not edit */
const VERSION = ${JSON.stringify(version)};
const BASE = ${JSON.stringify(BASE)};
const FILES = ${JSON.stringify(urls)};
const REF = new RegExp(${JSON.stringify(REF)}, "g");
// Build time first, so versions sort oldest → newest
const CACHE = "dalin-" + ${Date.now()} + "-" + VERSION;
const builtAt = (name) => Number(name.split("-")[1]) || 0; // older "dalin-<hash>" names count as oldest

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    try {
      // cache: "reload" = straight from the server. Otherwise the browser may hand back its own
      // 10-minute copy of the OLD pages, which point at old style files that no longer exist —
      // the app then opens with no styles once those copies expire.
      for (let i = 0; i < FILES.length; i += 20)
        await cache.addAll(FILES.slice(i, i + 20).map((u) => new Request(u, { cache: "reload" })));
      // Double-check: every page may only use files of this same version (a CDN that still serves
      // an old page right after publishing would cause the same breakage). If not, give up for now:
      // the current version keeps working and the browser tries again on a later visit.
      const have = new Set(FILES);
      for (const u of FILES.filter((f) => f.endsWith("/"))) {
        const html = await (await cache.match(u)).text();
        const stray = (html.match(REF) || []).find((r) => !have.has(r));
        if (stray) throw new Error("page " + u + " is from another version (" + stray + ")");
      }
    } catch (e) {
      await caches.delete(CACHE);
      throw e;
    }
    await self.skipWaiting();
  })());
});

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    // Keep the newest older version too: a screen still open on it can finish loading its files
    const old = (await caches.keys()).filter((k) => k.startsWith("dalin-") && k !== CACHE).sort((a, b) => builtAt(a) - builtAt(b));
    await Promise.all(old.slice(0, -1).map((k) => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== location.origin || !url.pathname.startsWith(BASE + "/")) return;

  if (req.mode === "navigate") {
    let path = url.pathname;
    if (!path.endsWith("/") && !/\\.[a-z0-9]+$/i.test(path)) path += "/";
    event.respondWith(
      caches.open(CACHE).then(async (cache) =>
        (await cache.match(path)) ||
        fetch(req).catch(async () => (await cache.match(BASE + "/pos/")) || (await cache.match(BASE + "/")) || Response.error()),
      ),
    );
    return;
  }

  // This version's copy, else the previous version's (a screen opened before the update), else the internet
  event.respondWith(
    caches.open(CACHE).then(async (cache) =>
      (await cache.match(req, { ignoreSearch: true })) || (await caches.match(req, { ignoreSearch: true })) || fetch(req),
    ),
  );
});
`;
writeFileSync(join(OUT, "sw.js"), sw);
console.log(`✓ sw.js: ${urls.length} files (${(bytes / 1024 / 1024).toFixed(2)} MB) cached for offline use, version ${version}`);
